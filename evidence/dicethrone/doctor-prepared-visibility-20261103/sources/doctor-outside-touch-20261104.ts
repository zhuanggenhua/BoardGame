import { test, expect } from '../framework';
import { captureEvidenceSourceIdentity } from '../framework/sourceIdentity';
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { initHeroState } from '../../src/games/dicethrone/domain/characters';
import { DOCTOR_STRANGE_CARDS } from '../../src/games/dicethrone/heroes/doctor_strange/cards';

test.use({ hasTouch: true, isMobile: true, viewport: { width: 812, height: 375 } });
test('奇异博士准备法术横屏触控隐藏与恢复', async ({ page, game }) => {
    test.setTimeout(120000);
    const output = resolve('temp/doctor-outside-touch-20261104');
    mkdirSync(output, { recursive: true });
    const random = { shuffle: <T>(a: T[]) => a, random: () => 0.5, d: (_n: number) => 1, range: (n: number, _m: number) => n };
    const ids = ['spell-flames-of-faltine', 'spell-rings-of-raggadorr', 'spell-vapors-of-valtorr'];
    await game.openTestGame('dicethrone', { playerID: '0', disableLocalAiAutomation: true, seat0: 'human', seat1: 'human' });
    expect(await page.evaluate(() => matchMedia('(pointer: coarse)').matches)).toBe(true);
    const player = initHeroState('0', 'doctor_strange', random);
    const opponent = initHeroState('1', 'monk', random);
    player.preparedSpells = ids.map(id => structuredClone(DOCTOR_STRANGE_CARDS.find(card => card.id === id)!));
    player.deck = DOCTOR_STRANGE_CARDS.filter(card => !ids.includes(card.id)).map(card => structuredClone(card));
    player.hand = [];
    await game.setupScene({ gameId: 'dicethrone', currentPlayer: '0', phase: 'main1', extra: { players: { '0': player, '1': opponent }, selectedCharacters: { '0': 'doctor_strange', '1': 'monk' }, hostStarted: true, readyPlayers: { '0': true, '1': true } } });
    const zone = page.locator('[data-prepared-spell-zone="public"]');
    await expect(zone.locator('[data-prepared-spell-card]')).toHaveCount(3);
    await zone.locator('[data-card-atlas-img]').first().waitFor({ state: 'attached', timeout: 30000 });
    const next = zone.locator('[data-prepared-spell-direction="next"]');
    const box = await next.boundingBox();
    expect(box && box.width >= 43.5 && box.height >= 43.5).toBe(true);
    const media: object[] = [];
    const capture = async (label: string) => {
        await page.evaluate(async () => { await document.fonts.ready; await Promise.all(document.getAnimations().filter(a => Number.isFinite(a.effect?.getComputedTiming().endTime)).map(a => a.finished.catch(() => {}))); });
        const file = resolve(output, label + '.png');
        const bytes = await page.screenshot({ path: file });
        media.push({ label, file, sha256: createHash('sha256').update(bytes).digest('hex'), control: box });
    };
    await capture('横屏触控三张');
    const scroll = zone.locator('.overflow-x-auto');
    await next.tap(); await expect.poll(() => scroll.evaluate(node => node.scrollLeft)).toBeGreaterThan(0);
    await next.tap();
    await expect.poll(() => scroll.evaluate(node => node.scrollWidth - node.clientWidth - node.scrollLeft)).toBeLessThan(2);
    await capture('横屏触控末张');
    const toggle = page.getByTestId('dt-prepared-spells-visibility');
    const toggleBox = await toggle.boundingBox();
    expect(toggleBox && toggleBox.width >= 43.5 && toggleBox.height >= 43.5).toBe(true);
    const savedScroll = await scroll.evaluate(node => node.scrollLeft);
    const savedCards = (await game.getState()).core.players['0'].preparedSpells.map((card: {id: string}) => card.id);
    await toggle.tap({ timeout: 5000 }); await expect(toggle).toHaveAttribute('aria-pressed', 'true');
    await expect(zone.locator('[data-prepared-spell-card]').last()).toBeHidden();
    expect((await game.getState()).core.players['0'].preparedSpells.map((card: {id: string}) => card.id)).toEqual(savedCards);
    await capture('横屏触控露出被动');
    await toggle.tap({ timeout: 5000 }); await expect(toggle).toHaveAttribute('aria-pressed', 'false');
    await expect.poll(() => scroll.evaluate(node => node.scrollLeft)).toBe(savedScroll);
    await capture('横屏触控恢复法术');
    await zone.locator(`[data-prepared-spell-card="${ids[2]}"]`).tap();
    await expect(page.getByTestId('board-magnify-overlay')).toBeVisible();
    await page.getByTestId('board-magnify-overlay-close').tap();
    await next.tap(); await expect.poll(() => scroll.evaluate(node => node.scrollLeft)).toBe(0);
    const identity = await captureEvidenceSourceIdentity(page, 'dicethrone');
    writeFileSync(resolve(output, 'capture.json'), JSON.stringify({ productAcceptance: 'not-claimed', identity, media }, null, 2));
});

