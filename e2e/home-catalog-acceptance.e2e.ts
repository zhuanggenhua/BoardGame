import { test, expect, initHome, login, switchStyle, openGame, capture, record } from './helpers/homeAcceptance';

for (const mobile of [false, true]) {
    const style = 'modern';
    const label = `${mobile ? '手机' : '桌面'}-${style === 'modern' ? '现代' : '经典'}`;
    test(`${label}搜索分类详情收藏返回及账户隔离持久化`, async ({ browser, accounts }, info) => {
        info.setTimeout(120_000);
        const context = await browser.newContext({ baseURL: info.project.use.baseURL, viewport: mobile ? { width: 375, height: 812 } : { width: 1920, height: 1080 }, hasTouch: mobile, isMobile: mobile });
        try {
            const page = await context.newPage(); await initHome(page);
            const search = page.getByRole('searchbox', { name: '搜索游戏' }).filter({ visible: true });
            await search.fill('不存在的验收游戏');
            await expect(page.getByRole('status').filter({ hasText: '没有找到匹配的游戏' })).toBeVisible();
            await search.fill('井字棋');
            await expect(page.locator('[data-game-id="smashup"]')).toHaveCount(0);
            await capture(page, `${label}-搜索`);
            await page.getByRole('button', { name: '抽象', exact: true }).click();
            await openGame(page, style, 'tictactoe', '井字棋', mobile);
            await page.getByTestId('game-details-close-button').click();
            await expect(search).toHaveValue('井字棋');
            await expect(page.getByRole('button', { name: '抽象', exact: true })).toHaveAttribute('aria-pressed', 'true');
            await capture(page, `${label}-搜索分类返回`);
            await search.fill('');
            await page.getByRole('button', { name: '卡牌', exact: true }).click();
            await expect(page.locator('[data-game-id="tictactoe"]')).toHaveCount(0);
            await page.getByRole('button', { name: '全部游戏', exact: true }).click();
            const gameControl = page.getByRole('button', { name: '井字棋', exact: true }).last();
            await gameControl.scrollIntoViewIfNeeded();
            const returnScroll = await page.evaluate(() => window.scrollY);
            await openGame(page, style, 'tictactoe', '井字棋', mobile);
            const details = page.getByTestId('game-details-modal-root');
            const favorite = details.getByRole('button', { name: '收藏：井字棋', exact: true });
            await favorite.click();
            await expect(details.getByRole('button', { name: '移出收藏：井字棋', exact: true })).toHaveAttribute('aria-pressed', 'true');
            await capture(page, `${label}-详情收藏`);
            await page.keyboard.press('Escape');
            await expect(page).not.toHaveURL(/game=tictactoe/);
            await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(returnScroll);
            await expect(search).toHaveValue('');
            await page.getByRole('button', { name: '收藏库', exact: true }).click();
            await expect(page).toHaveURL(/section=library/);
            await expect(page.locator('.platform-home-main--library')).toBeVisible();
            await expect(page.locator('[data-game-id="tictactoe"]')).toBeVisible();
            await page.getByRole('searchbox', { name: '搜索游戏' }).filter({ visible: true }).fill('井');
            await expect(page.getByRole('searchbox', { name: '搜索游戏' }).filter({ visible: true })).toHaveValue('井');
            const libraryInput = await page.getByRole('searchbox', { name: '搜索游戏' }).filter({ visible: true }).elementHandle();
            await record(`${label}-收藏返回前`, { url: page.url(), query: await libraryInput!.inputValue(), sidebar: await libraryInput!.evaluate(node => Boolean(node.closest('.platform-library-sidebar'))) });
            await openGame(page, style, 'tictactoe', '井字棋', mobile);
            await record(`${label}-收藏详情中`, { url: page.url(), inputConnected: await libraryInput!.evaluate(node => node.isConnected), inputValue: await libraryInput!.inputValue() });
            await page.getByTestId('game-details-close-button').click();
            await record(`${label}-收藏返回后`, { url: page.url(), queries: await page.getByRole('searchbox', { name: '搜索游戏' }).filter({ visible: true }).evaluateAll(nodes => nodes.map(node => (node as HTMLInputElement).value)) });
            await expect(page.getByRole('searchbox', { name: '搜索游戏' }).filter({ visible: true })).toHaveValue('井');
            await expect(page.getByRole('button', { name: '收藏库', exact: true })).toHaveAttribute('aria-current', 'page');
            await expect(page.locator('[data-game-id="tictactoe"]')).toBeVisible();
            await page.getByRole('searchbox', { name: '搜索游戏' }).filter({ visible: true }).fill('');
            await page.reload();
            await expect(page.locator('[data-game-id="tictactoe"]')).toBeVisible();
            await capture(page, `${label}-访客收藏刷新`);
            const aliceRead = page.waitForResponse(r => r.url().endsWith('/auth/user-settings/library') && r.request().method() === 'GET');
            await login(page, accounts.alice);
            const aliceLibrary = await aliceRead;
            expect(aliceLibrary.ok()).toBe(true); expect((await aliceLibrary.json()).gameIds).toEqual([]);
            await page.getByRole('button', { name: '收藏库', exact: true }).click();
            await expect(page.locator('[data-game-id="tictactoe"]')).toHaveCount(0);
            await page.getByRole('button', { name: '发现', exact: true }).click();
            await openGame(page, style, 'tictactoe', '井字棋', mobile);
            const write = page.waitForResponse(r => r.url().endsWith('/auth/user-settings/library') && r.request().method() === 'PUT');
            await details.getByRole('button', { name: '收藏：井字棋', exact: true }).click();
            expect((await write).ok()).toBe(true);
            await page.keyboard.press('Escape');
            await page.reload();
            await page.getByRole('button', { name: '收藏库', exact: true }).click();
            await expect(page.locator('[data-game-id="tictactoe"]')).toBeVisible();
            await page.getByTestId('user-menu-trigger').click();
            await page.locator('[data-user-menu-panel] > button').last().click();
            await expect(page.getByTestId('user-menu-trigger')).toHaveCount(0);
            const bobRead = page.waitForResponse(r => r.url().endsWith('/auth/user-settings/library') && r.request().method() === 'GET');
            await login(page, accounts.bob);
            const bobLibrary = await bobRead;
            expect(bobLibrary.ok()).toBe(true); expect((await bobLibrary.json()).gameIds).toEqual([]);
            await page.getByRole('button', { name: '收藏库', exact: true }).click();
            await expect(page.locator('[data-game-id="tictactoe"]')).toHaveCount(0);
            await capture(page, `${label}-账户切换空收藏`);
            await page.getByTestId('user-menu-trigger').click();
            await page.locator('[data-user-menu-panel] > button').last().click();
            await login(page, accounts.alice);
            await page.getByRole('button', { name: '收藏库', exact: true }).click();
            await expect(page.locator('[data-game-id="tictactoe"]')).toBeVisible();
            await openGame(page, style, 'tictactoe', '井字棋', mobile);
            await details.getByRole('button', { name: '移出收藏：井字棋', exact: true }).click();
            await expect(details.getByRole('button', { name: '收藏：井字棋', exact: true })).toBeEnabled();
            await record(label, { search: true, category: true, details: true, nonEmptyQueryCategoryReturn: true, libraryQueryReturn: true, returnScroll, guestPersistence: true, guestAccountIsolation: true, accountPersistence: true, samePageSwitchIsolation: true, authoritativeIsolationReads: [aliceLibrary.status(), bobLibrary.status()] });
        } finally { await context.close(); }
    });
}

for (const mobile of [false, true]) {
    test(`${mobile ? '手机' : '桌面'}经典保持原大厅，详情收藏隔离及刷新持久化`, async ({ browser, accounts }, info) => {
        info.setTimeout(90_000);
        const context = await browser.newContext({ baseURL: info.project.use.baseURL, viewport: mobile ? { width: 375, height: 812 } : { width: 1920, height: 1080 }, hasTouch: mobile, isMobile: mobile });
        try {
            const page = await context.newPage();
            await initHome(page);
            await switchStyle(page, 'classic');
            await expect(page.getByRole('searchbox')).toHaveCount(0);
            await expect(page.getByRole('button', { name: '收藏库', exact: true })).toHaveCount(0);
            await page.getByRole('button', { name: '抽象', exact: true }).click();
            await expect(page.locator('[data-game-id="smashup"]')).toHaveCount(0);
            await openGame(page, 'classic', 'tictactoe', '井字棋', mobile);
            const details = page.getByTestId('game-details-modal-root');
            await details.getByRole('button', { name: '收藏：井字棋', exact: true }).click();
            await page.getByTestId('game-details-close-button').click();
            await expect(page.getByRole('button', { name: '抽象', exact: true })).toHaveAttribute('aria-pressed', 'true');
            await page.reload();
            await openGame(page, 'classic', 'tictactoe', '井字棋', mobile);
            await expect(details.getByRole('button', { name: '移出收藏：井字棋', exact: true })).toHaveAttribute('aria-pressed', 'true');
            await page.getByTestId('game-details-close-button').click();
            await login(page, accounts.alice);
            await openGame(page, 'classic', 'tictactoe', '井字棋', mobile);
            await expect(details.getByRole('button', { name: '收藏：井字棋', exact: true })).toHaveAttribute('aria-pressed', 'false');
            const write = page.waitForResponse(r => r.url().endsWith('/auth/user-settings/library') && r.request().method() === 'PUT');
            await details.getByRole('button', { name: '收藏：井字棋', exact: true }).click();
            expect((await write).ok()).toBe(true);
            await page.getByTestId('game-details-close-button').click();
            await page.reload();
            await openGame(page, 'classic', 'tictactoe', '井字棋', mobile);
            await expect(details.getByRole('button', { name: '移出收藏：井字棋', exact: true })).toHaveAttribute('aria-pressed', 'true');
            await page.getByTestId('game-details-close-button').click();
            await page.getByTestId('user-menu-trigger').click();
            await page.locator('[data-user-menu-panel] > button').last().click();
            await login(page, accounts.bob);
            await openGame(page, 'classic', 'tictactoe', '井字棋', mobile);
            await expect(details.getByRole('button', { name: '收藏：井字棋', exact: true })).toHaveAttribute('aria-pressed', 'false');
            await page.getByTestId('game-details-close-button').click();
            await page.getByTestId('user-menu-trigger').click();
            await page.locator('[data-user-menu-panel] > button').last().click();
            await login(page, accounts.alice);
            await openGame(page, 'classic', 'tictactoe', '井字棋', mobile);
            await expect(details.getByRole('button', { name: '移出收藏：井字棋', exact: true })).toHaveAttribute('aria-pressed', 'true');
            const remove = page.waitForResponse(r => r.url().endsWith('/auth/user-settings/library') && r.request().method() === 'PUT');
            await details.getByRole('button', { name: '移出收藏：井字棋', exact: true }).click();
            expect((await remove).ok()).toBe(true);
            await record(`${mobile ? '手机' : '桌面'}经典纠正行为`, { originalLobby: true, noAddedSearchOrLibrary: true, categoryDetailsReturn: true, guestPersistence: true, guestAccountIsolation: true, accountPersistence: true, bobIsolation: true, aliceRestored: true, noClassicScreenshots: '按用户要求不重新交付经典旧图' });
        } finally { await context.close(); }
    });
}
